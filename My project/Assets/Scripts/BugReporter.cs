using UnityEngine;
using UnityEngine.UI;
using UnityEngine.Networking;
using System.Collections;
using TMPro;

public class BugReporter : MonoBehaviour
{
    [Header("Configuration")]
    [Tooltip("Create a Webhook in Discord (Channel Settings > Integrations) and paste URL here.")]
    public string discordWebhookURL = "";

    [Header("UI References")]
    public GameObject reportPanel;
    public TMP_InputField userNoteInput;
    public Button sendButton;
    public TextMeshProUGUI statusText;

    private bool isSending = false;

    // Toggle this from your Pause Menu button
    public void TogglePanel()
    {
        if (reportPanel == null) return;
        bool isActive = !reportPanel.activeSelf;
        reportPanel.SetActive(isActive);

        if (isActive)
        {
            // Ensure it renders on top of everything else (like the Pause Menu)
            reportPanel.transform.SetAsLastSibling();

            // Pause if opening
            if (GameManager.Instance) Time.timeScale = 0f;
            if (userNoteInput) userNoteInput.Select();
        }
        else
        {
            // Unpause if closing (ONLY if we were playing).
            // If we were paused (e.g. opened from Pause Menu), we stay paused.
            if (GameManager.Instance && GameManager.Instance.currentState == GameManager.GameState.Playing)
                Time.timeScale = 1f;
        }
    }

    public void SendReport()
    {
        if (isSending) return;
        if (string.IsNullOrEmpty(discordWebhookURL))
        {
            if (statusText) statusText.text = "Setup Error: No Webhook URL.";
            return;
        }

        StartCoroutine(SendToDiscordEmbed());
    }

    IEnumerator SendToDiscordEmbed()
    {
        isSending = true;
        if (sendButton) sendButton.interactable = false;
        if (statusText) statusText.text = "Sending Report...";

        // 1. GATHER DATA
        string userNote = userNoteInput.text;
        if (string.IsNullOrWhiteSpace(userNote)) userNote = "No details provided.";

        string sceneName = UnityEngine.SceneManagement.SceneManager.GetActiveScene().name;
        string debugInfo = "N/A";

        if (GameManager.Instance)
        {
            // Use the formatted debug info from GameManager
            debugInfo = GameManager.Instance.GetDebugInfo();
        }

        // Clean up strings for JSON
        string cleanNote = EscapeJson(userNote);
        string cleanDebug = EscapeJson(debugInfo);

        // 2. CONSTRUCT JSON PAYLOAD (Discord Embed Format)
        // We build this manually to avoid external JSON library dependencies.
        // Color 16711680 is Red.

        string jsonPayload = $@"
        {{
            ""username"": ""Bug Bot"",
            ""embeds"": [
                {{
                    ""title"": ""Bug Report"",
                    ""color"": 16711680,
                    ""fields"": [
                        {{
                            ""name"": ""User Note"",
                            ""value"": ""{cleanNote}"",
                            ""inline"": false
                        }},
                        {{
                            ""name"": ""Scene"",
                            ""value"": ""{sceneName}"",
                            ""inline"": true
                        }},
                        {{
                            ""name"": ""System"",
                            ""value"": ""{Application.platform} | {Screen.width}x{Screen.height}"",
                            ""inline"": true
                        }},
                        {{
                            ""name"": ""Game State"",
                            ""value"": ""```{cleanDebug}```"",
                            ""inline"": false
                        }}
                    ],
                    ""footer"": {{
                        ""text"": ""Generated by Unity BugReporter""
                    }}
                }}
            ]
        }}";

        // 3. SEND REQUEST
        using (UnityWebRequest www = new UnityWebRequest(discordWebhookURL, "POST"))
        {
            byte[] bodyRaw = System.Text.Encoding.UTF8.GetBytes(jsonPayload);
            www.uploadHandler = new UploadHandlerRaw(bodyRaw);
            www.downloadHandler = new DownloadHandlerBuffer();
            www.SetRequestHeader("Content-Type", "application/json");

            yield return www.SendWebRequest();

            if (www.result == UnityWebRequest.Result.Success)
            {
                if (statusText) statusText.text = "Report Sent!";
                Debug.Log("Discord Webhook sent successfully.");
                yield return new WaitForSeconds(1.5f);
                TogglePanel(); // Close UI
                userNoteInput.text = ""; // Reset
            }
            else
            {
                if (statusText) statusText.text = "Failed to Send.";
                Debug.LogError($"Webhook Error: {www.error}\nResponse: {www.downloadHandler.text}");
            }
        }

        if (sendButton) sendButton.interactable = true;
        isSending = false;
    }

    // Helper to prevent JSON breaking on quotes or newlines
    private string EscapeJson(string s)
    {
        if (string.IsNullOrEmpty(s)) return "";
        return s
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\n", "\\n")
            .Replace("\r", "");
    }
}